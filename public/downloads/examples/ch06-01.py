# Pembangkitan Deret Bilangan Dasar dengan range()
# File: ch06-01.py

print("1. Deret default range(5):")
for i in range(5):
    print(i, end=" ")
print("\n")

print("2. Deret dengan batas start dan stop range(1, 6):")
for i in range(1, 6):
    print(i, end=" ")
print("\n")

print("3. Deret dengan langkah (step) kelipatan 5 range(10, 31, 5):")
for i in range(10, 31, 5):
    print(i, end=" ")
print("\n")

print("4. Deret hitung mundur (countdown) range(5, 0, -1):")
for i in range(5, 0, -1):
    print(i, end=" ")
print()

