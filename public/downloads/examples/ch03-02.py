rsrp_terukur = -88
ambang_batas = -90

print("RSRP Terukur:", rsrp_terukur, "dBm")
print("Ambang Batas:", ambang_batas, "dBm")

print("rsrp == ambang:", rsrp_terukur == ambang_batas)
print("rsrp != ambang:", rsrp_terukur != ambang_batas)
print("rsrp > ambang (Lebih Baik):", rsrp_terukur > ambang_batas)
print("rsrp < ambang (Lebih Buruk):", rsrp_terukur < ambang_batas)
print("rsrp >= ambang:", rsrp_terukur >= ambang_batas)
print("rsrp <= ambang:", rsrp_terukur <= ambang_batas)

