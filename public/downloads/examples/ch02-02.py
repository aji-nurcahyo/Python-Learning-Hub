jumlah_antena = 4              # int (bilangan bulat)
frekuensi_ghz = 2.45           # float (bilangan riil desimal)
nama_protokol = "IEEE 802.11"  # str (untaian karakter teks)
status_aktif = True            # bool (nilai logika kebenaran)

print("jumlah_antena:", jumlah_antena, "-> tipe:", type(jumlah_antena).__name__)
print("frekuensi_ghz:", frekuensi_ghz, "-> tipe:", type(frekuensi_ghz).__name__)
print("nama_protokol:", nama_protokol, "-> tipe:", type(nama_protokol).__name__)
print("status_aktif:", status_aktif, "-> tipe:", type(status_aktif).__name__)
